import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { Script } from 'node:vm';
const root = new URL('../', import.meta.url);
const modules = ['core','send','sidebar','keyboard','tree'];
const bodies = await Promise.all(modules.map(name=>readFile(new URL(`src/${name}.cjs`,root),'utf8')));
const client = await readFile(new URL('src/client.cjs', root), 'utf8');
const css = await readFile(new URL('src/style.css', root), 'utf8');
const embedded=modules.map((name,i)=>`const ${name}Module={exports:{}};\n(function(module,exports){\n${bodies[i]}\n})(${name}Module,${name}Module.exports);\n`).join('');
const resolver=modules.map(name=>`request==='./${name}.cjs'?${name}Module.exports:`).join('');
const output = `// Generated by scripts/build.mjs. Edit src/, then npm run build.\nwindow.__ModuleLoader__.load({ id: "dsh-treechat", factory(require) {\n${embedded}const module={exports:{}};\n(function(module,exports,require){\nconst TREECHAT_CSS=${JSON.stringify(css)};\n${client}\n})(module,module.exports,request=>${resolver}require(request));\nreturn module.exports;\n}});\n`;
new Script(output, {filename:'lib/client.js'});
await mkdir(new URL('lib/', root), { recursive: true });
await writeFile(new URL('lib/client.js', root), output);
console.log(`Built ${fileURLToPath(new URL('lib/client.js', root))} (${Buffer.byteLength(output)} bytes)`);
